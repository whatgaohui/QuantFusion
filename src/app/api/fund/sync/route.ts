/**
 * Determine exchange from fund code.
 * Codes starting with 5/6 → SH (Shanghai)
 * Codes starting with 0/1/2/3 → SZ (Shenzhen)
 */
function getExchange(code: string): string {
  const firstChar = code[0];
  if (firstChar === '5' || firstChar === '6') return 'SH';
  if (firstChar === '0' || firstChar === '1' || firstChar === '2' || firstChar === '3') return 'SZ';
  return 'SZ'; // default
}

/**
 * Determine isEtf from fundType and fund name.
 * EastMoney returns types like "指数型-股票" for ETFs, so we also check the name.
 * On-market ETF codes follow patterns: 51xxxx (SH), 159xxx (SZ), 588xxx (SH)
 */
function isEtfFund(fundType: string, name: string, code: string): boolean {
  const ft = fundType.toUpperCase();

  // Check if fundType explicitly says ETF
  if (ft === 'ETF' || ft.includes('ETF')) return true;

  // Check if name contains ETF
  if (name.toUpperCase().includes('ETF')) return true;

  // Check common ETF code patterns (on-market ETFs in China)
  // 510xxx, 511xxx, 512xxx, 513xxx, 515xxx, 516xxx, 518xxx, 588xxx (Shanghai)
  // 159xxx (Shenzhen)
  if (/^(51[0-8]\d{3}|588\d{3}|159\d{3})$/.test(code)) return true;

  return false;
}

/**
 * Determine isOnMarket from fundType, name, and code.
 * On-market funds include ETFs (listed on exchange) and LOF funds.
 * EastMoney types don't always say "ETF" or "LOF", so we check names and codes too.
 */
function isOnMarketFund(fundType: string, name: string, code: string): boolean {
  const ft = fundType.toUpperCase();

  // Check if fundType explicitly says ETF or LOF
  if (ft === 'ETF' || ft.includes('ETF') || ft === 'LOF' || ft.includes('LOF')) return true;

  // Check if name contains ETF or (LOF)
  const nameUpper = name.toUpperCase();
  if (nameUpper.includes('ETF') || nameUpper.includes('(LOF)') || name.includes('LOF')) return true;

  // Check common on-market ETF code patterns
  if (/^(51[0-8]\d{3}|588\d{3}|159\d{3})$/.test(code)) return true;

  // Check common LOF code patterns
  // 161xxx, 162xxx, 163xxx, 164xxx, 165xxx, 166xxx, 167xxx, 168xxx (Shenzhen LOF)
  // 501xxx (Shanghai LOF)
  if (/^(16[1-8]\d{3}|501\d{3})$/.test(code)) return true;

  return false;
}

/**
 * Parse EastMoney fund code search JS response.
 * Format: var r = [["000001","HXCZHH","华夏成长混合","混合型-偏股","HUAXIACHENGZHANGHUNHE"],...]
 */
function parseEastMoneyResponse(text: string): [string, string, string, string][] {
  const match = text.match(/var\s+r\s*=\s*(\[[\s\S]*\]);?/);
  if (!match) return [];

  try {
    const data = JSON.parse(match[1]);
    if (!Array.isArray(data)) return [];

    return data
      .filter((item: unknown[]): item is [string, string, string, string] =>
        Array.isArray(item) && item.length >= 4
      )
      .map((item: [string, string, string, string]) => [
        item[0],  // code
        item[4] || item[1] || '', // pinyin (full first, then abbreviation)
        item[2],  // name
        item[3],  // fundType
      ]);
  } catch {
    return [];
  }
}

/**
 * POST /api/fund/sync
 * Sync fund data from EastMoney or fallback data into the Fund database.
 */
export async function POST() {
  try {
    let funds: [string, string, string, string][] = [];
    let source = 'eastmoney';

    // Try fetching from EastMoney API
    try {
      const response = await fetch('https://fund.eastmoney.com/js/fundcode_search.js', {
        signal: AbortSignal.timeout(15000), // 15 second timeout
        headers: {
          'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
          'Referer': 'https://fund.eastmoney.com/',
        },
      });

      if (response.ok) {
        const text = await response.text();
        const parsed = parseEastMoneyResponse(text);
        if (parsed.length > 0) {
          funds = parsed;
        }
      }
    } catch (error) {
      console.warn('EastMoney API fetch failed, using fallback data:', error);
    }

    // Use fallback if EastMoney didn't return data
    if (funds.length === 0) {
      funds = FALLBACK_FUNDS;
      source = 'fallback';
    }

    // Upsert all funds into the database
    let syncedCount = 0;
    let etfCount = 0;
    let onMarketCount = 0;

    // Process in batches of 50 to avoid SQLite limitations
    const BATCH_SIZE = 50;
    for (let i = 0; i < funds.length; i += BATCH_SIZE) {
      const batch = funds.slice(i, i + BATCH_SIZE);

      for (const [code, pinyin, name, fundType] of batch) {
        const isEtf = isEtfFund(fundType, name, code);
        const isOnMarket = isOnMarketFund(fundType, name, code);
        const exchange = getExchange(code);

        if (isEtf) etfCount++;
        if (isOnMarket) onMarketCount++;

        try {
          await db.fund.upsert({
            where: { code },
            update: {
              name,
              pinyin: pinyin.toLowerCase(),
              fundType,
              market: 'A',
              isOnMarket,
              isEtf,
              exchange,
            },
            create: {
              code,
              name,
              pinyin: pinyin.toLowerCase(),
              fundType,
              market: 'A',
              isOnMarket,
              isEtf,
              exchange,
            },
          });
          syncedCount++;
        } catch (err) {
          console.error(`Failed to upsert fund ${code}:`, err);
        }
      }
    }

    return NextResponse.json({
      success: true,
      source,
      stats: {
        total: syncedCount,
        etfCount,
        onMarketCount,
      },
    });
  } catch (error) {
    console.error('Fund sync error:', error);
    return NextResponse.json(
      { error: 'Failed to sync fund data', details: String(error) },
      { status: 500 }
    );
  }
}

/**
 * GET /api/fund/sync
 * Returns sync status (total fund count in DB).
 */
export async function GET() {
  try {
    const total = await db.fund.count();
    const etfCount = await db.fund.count({ where: { isEtf: true } });
    const onMarketCount = await db.fund.count({ where: { isOnMarket: true } });

    return NextResponse.json({
      synced: true,
      stats: {
        total,
        etfCount,
        onMarketCount,
      },
    });
  } catch (error) {
    console.error('Fund sync status error:', error);
    return NextResponse.json(
      { error: 'Failed to get fund sync status' },
      { status: 500 }
    );
  }
}
